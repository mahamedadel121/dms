import { describe, expect, it } from 'vitest';
import { amountToArabicWords as w } from './amountWords';

describe('amountToArabicWords', () => {
  const T = ' فقط لا غير';
  it.each([
    ['1250.50', 'ألف ومائتان وخمسون جنيهاً مصرياً وخمسون قرشاً' + T],
    ['0', 'صفر جنيه مصري' + T],
    ['0.00', 'صفر جنيه مصري' + T],
    ['1', 'جنيه مصري واحد' + T],
    ['2', 'جنيهان مصريان' + T],
    ['3', 'ثلاثة جنيهات مصرية' + T],
    ['11', 'أحد عشر جنيهاً مصرياً' + T],
    ['21', 'واحد وعشرون جنيهاً مصرياً' + T],
    ['100', 'مائة جنيه مصري' + T],
    ['200', 'مائتان جنيه مصري' + T],
    ['1000', 'ألف جنيه مصري' + T],
    ['2000', 'ألفان جنيه مصري' + T],
    ['3000', 'ثلاثة آلاف جنيه مصري' + T],
    ['11000', 'أحد عشر ألفاً جنيه مصري' + T],
    ['1000000', 'مليون جنيه مصري' + T],
    ['2500000', 'مليونان وخمسمائة ألف جنيه مصري' + T],
    ['0.01', 'قرش واحد' + T],
    ['0.02', 'قرشان' + T],
    ['0.05', 'خمسة قروش' + T],
    ['0.75', 'خمسة وسبعون قرشاً' + T],
    ['5.01', 'خمسة جنيهات مصرية وقرش واحد' + T],
  ])('%s', (a, expected) => {
    expect(w(a)).toBe(expected);
  });
  it('rejects bad input', () => {
    expect(() => w('-1')).toThrow();
    expect(() => w('abc')).toThrow();
  });
});
